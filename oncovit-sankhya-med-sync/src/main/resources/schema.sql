DROP TABLE IF EXISTS sankhya_sync_log;
DROP TABLE IF EXISTS movimentacoes;
DROP TABLE IF EXISTS lotes;
DROP TABLE IF EXISTS medicamentos;

CREATE TABLE medicamentos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_sankhya VARCHAR(50) NOT NULL UNIQUE,
    codigo_sku VARCHAR(50),
    nome_comercial VARCHAR(150) NOT NULL,
    principio_ativo VARCHAR(150) NOT NULL,
    dosagem VARCHAR(50),
    forma_farmaceutica VARCHAR(100),
    categoria VARCHAR(50) NOT NULL,
    tipo_armazenamento VARCHAR(30) NOT NULL,
    temperatura_minima NUMERIC(4,1) NOT NULL,
    temperatura_maxima NUMERIC(4,1) NOT NULL,
    registro_anvisa VARCHAR(30),
    unidade_medida VARCHAR(30) NOT NULL DEFAULT 'FRASCO_AMPOLA',
    criado_em TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_med_armazenamento CHECK (tipo_armazenamento IN ('CADEIA_DE_FRIO', 'AMBIENTE')),
    CONSTRAINT chk_med_temperatura CHECK (temperatura_minima <= temperatura_maxima)
);

CREATE TABLE lotes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    medicamento_id BIGINT NOT NULL,
    numero_lote VARCHAR(50) NOT NULL UNIQUE,
    data_fabricacao DATE NOT NULL,
    data_validade DATE NOT NULL,
    quantidade_inicial INT NOT NULL,
    quantidade_atual INT NOT NULL,
    status_lote VARCHAR(30) NOT NULL,
    fornecedor VARCHAR(150),
    preco_unitario NUMERIC(12,2) NOT NULL DEFAULT 0.00,
    version BIGINT DEFAULT 0 NOT NULL,
    criado_em TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    atualizado_em TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_lotes_medicamento FOREIGN KEY (medicamento_id) REFERENCES medicamentos(id) ON DELETE RESTRICT,
    CONSTRAINT chk_lote_datas CHECK (data_validade > data_fabricacao),
    CONSTRAINT chk_lote_qtd_ini CHECK (quantidade_inicial >= 0),
    CONSTRAINT chk_lote_qtd_atual CHECK (quantidade_atual >= 0 AND quantidade_atual <= quantidade_inicial),
    CONSTRAINT chk_lote_status CHECK (status_lote IN ('QUARENTENA', 'LIBERADO', 'BLOQUEADO', 'REJEITADO', 'VENCIDO'))
);

CREATE TABLE movimentacoes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lote_id BIGINT NOT NULL,
    tipo_movimentacao VARCHAR(50) NOT NULL,
    quantidade INT NOT NULL,
    motivo VARCHAR(255),
    documento_referencia VARCHAR(100),
    usuario_responsavel VARCHAR(100) NOT NULL,
    data_hora TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_mov_lote FOREIGN KEY (lote_id) REFERENCES lotes(id) ON DELETE RESTRICT,
    CONSTRAINT chk_mov_qtd CHECK (quantidade > 0),
    CONSTRAINT chk_mov_tipo CHECK (tipo_movimentacao IN ('ENTRADA_NOTA', 'BAIXA_SANKHYA_VENDA', 'PERDA_AVARIA', 'VENCIMENTO', 'AJUSTE_INVENTARIO', 'ENTRADA', 'SAIDA_VENDA'))
);

CREATE TABLE sankhya_sync_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    timestamp_sync TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    endpoint VARCHAR(100) NOT NULL,
    numero_nota BIGINT,
    numero_lote VARCHAR(50) NOT NULL,
    quantidade INT NOT NULL,
    status_transacao VARCHAR(50) NOT NULL,
    status_http INT NOT NULL,
    mensagem_retorno VARCHAR(500),
    payload_requisicao TEXT,
    payload_resposta TEXT
);

CREATE INDEX idx_med_codigo_sankhya ON medicamentos(codigo_sankhya);
CREATE INDEX idx_med_armazenamento ON medicamentos(tipo_armazenamento);
CREATE INDEX idx_lotes_medicamento ON lotes(medicamento_id);
CREATE INDEX idx_lotes_validade ON lotes(data_validade);
CREATE INDEX idx_lotes_status ON lotes(status_lote);
CREATE INDEX idx_lotes_status_validade ON lotes(status_lote, data_validade);
CREATE INDEX idx_mov_lote ON movimentacoes(lote_id);
CREATE INDEX idx_mov_data_hora ON movimentacoes(data_hora);
CREATE INDEX idx_sync_numero_nota ON sankhya_sync_log(numero_nota);
CREATE INDEX idx_sync_numero_lote ON sankhya_sync_log(numero_lote);
CREATE INDEX idx_sync_timestamp ON sankhya_sync_log(timestamp_sync);
CREATE INDEX idx_sync_status ON sankhya_sync_log(status_transacao);
